# 一次最多扩展成多少个词，防止关键词很长时 SQL 条件爆炸
MAX_TERMS = 8


def expand_terms(keyword):
    """
    把关键词扩展成用于 LIKE 查询的词列表，第一个元素一定是原始关键词。
    ' ' 分隔的多关键词按整串匹配，不做拆分（美食名本身很少带空格）。
    """
    kw = (keyword or '').strip()
    if not kw:
        return []

    terms = {kw}
    for group in SYNONYM_GROUPS:
        if any(alias in kw for alias in group):
            terms.update(group)
            if len(terms) >= MAX_TERMS:
                break

    others = sorted(terms - {kw}, key=len, reverse=True)
    return ([kw] + others)[:MAX_TERMS]


def expand_note(keyword):
    """除原始关键词外，本次额外参与检索的同义词（页面提示用）"""
    return [t for t in expand_terms(keyword)[1:]]
