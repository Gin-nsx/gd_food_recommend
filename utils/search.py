# utils/search.py
# 搜索词扩展：粤菜的同物异名、口语叫法特别多。
# 用户在搜索框里敲「白斩鸡」，库里只写了「白切鸡」，直接 LIKE 就是零结果；
# 敲「皮皮虾」也搜不到库里的「濑尿虾」。
#
# 做法：维护一份同义词组，只要关键词命中组里任意一个词条，
# 就把整组词都加进 OR 条件里一起查——不加权、不改排序，只是把召回补回来。

# 每组内的词互为同义，第一个作为「标准叫法」
